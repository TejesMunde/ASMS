#!/usr/bin/env bash
#
# Assignment Server Management System (ASMS)
# Module: provision_faculty.sh
# Version: 2.0.0
#
# Creates faculty accounts.
#
# Faculty get FACULTY_GROUP as a SUPPLEMENTARY group and keep a conventional
# per-user primary group. Students are the opposite -- students group is
# their primary -- which is what keeps student audit rules and student
# enumeration from ever picking up a faculty account.
#
# Faculty read access to submissions comes from the g:<faculty>:rX ACL that
# configure_mounts.sh applies to every student archive. Because that ACL
# names the GROUP, a faculty member created after the students were
# provisioned gets access immediately, with no re-run needed.
#
# Usage:
#   provision_faculty.sh                     interactive menu
#   provision_faculty.sh --csv FILE
#   provision_faculty.sh --users smith,jones
#

set -Eeuo pipefail

ASMS_MODULE_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"

# shellcheck source=utils.sh
source "${ASMS_MODULE_DIR}/utils.sh"
# shellcheck source=logger.sh
source "${ASMS_MODULE_DIR}/logger.sh"

require_root
load_config

PROVISIONED=0
FAILED=0

# ---------------------------------------------------------------------------
# Credentials
# ---------------------------------------------------------------------------

ensure_credential_store() {
    install -d -o root -g root -m "$CREDENTIAL_DIR_MODE" "$CREDENTIAL_DIR"

    if [[ ! -s "$FACULTY_CREDENTIALS" ]]; then
        printf 'username,name,password,created_at\n' > "$FACULTY_CREDENTIALS"
    fi

    chown root:root "$FACULTY_CREDENTIALS"
    chmod "$CREDENTIAL_FILE_MODE" "$FACULTY_CREDENTIALS"
}

credential_recorded() {
    [[ -f "$FACULTY_CREDENTIALS" ]] &&
        awk -F',' -v u="$1" 'NR > 1 && $1 == u { found = 1 } END { exit !found }' \
            "$FACULTY_CREDENTIALS"
}

record_credential() {
    local username="$1" password="$2" name="$3"

    credential_recorded "$username" && return 0

    # The display name is quoted and its own quotes doubled, so a name
    # containing a comma cannot shift the password into the wrong column.
    name="${name//\"/\"\"}"

    printf '%s,"%s",%s,%s\n' \
        "$username" "$name" "$password" "$(timestamp)" \
        >> "$FACULTY_CREDENTIALS"

    chmod "$CREDENTIAL_FILE_MODE" "$FACULTY_CREDENTIALS"
}

# ---------------------------------------------------------------------------

ensure_faculty_group() {
    group_exists "$FACULTY_GROUP" && return 0

    groupadd "$FACULTY_GROUP"
    log_action "CREATE_GROUP" "$FACULTY_GROUP" "SUCCESS"
    success "Created faculty group: $FACULTY_GROUP"
}

provision_faculty_account() {
    local username="$1"
    local display_name="${2:-Faculty}"

    validate_username "$username" || { FAILED=$((FAILED + 1)); return 1; }

    if user_exists "$username"; then
        # An existing student must not be promoted to faculty by this
        # module: it would leave the account holding a submission archive
        # while also being able to read everyone else's.
        if is_student_user "$username"; then
            error "$username is a student account; refusing to add it to $FACULTY_GROUP."
            log_action "PROVISION_FACULTY" "$username" "REFUSED_IS_STUDENT"
            FAILED=$((FAILED + 1))
            return 1
        fi

        usermod -aG "$FACULTY_GROUP" "$username"

        info "$username already exists; faculty group membership ensured."
        log_action "PROVISION_FACULTY" "$username" "EXISTING_UPDATED"
        return 0
    fi

    local password
    password="$(generate_password)"

    # umask 077 for the useradd call only: --create-home otherwise creates
    # the home directory at the distro default mode before it is chmod'd
    # to 0700 below. The subshell keeps the umask change from leaking into
    # the rest of this script.
    if ! (
        umask 077
        useradd \
            --create-home \
            --shell "$DEFAULT_SHELL" \
            --groups "$FACULTY_GROUP" \
            --comment "$display_name" \
            "$username"
    ); then
        error "Failed to create faculty account: $username"
        log_action "PROVISION_FACULTY" "$username" "FAILED_USERADD"
        FAILED=$((FAILED + 1))
        return 1
    fi

    if ! printf '%s:%s\n' "$username" "$password" | chpasswd; then
        userdel -r "$username" >/dev/null 2>&1 || true
        error "Failed to set password for $username; account rolled back."
        log_action "PROVISION_FACULTY" "$username" "FAILED_PASSWORD"
        FAILED=$((FAILED + 1))
        return 1
    fi

    # The password just set was generated by this module, not chosen by the
    # faculty member, so a change is mandatory before it can be used again.
    chage -d 0 "$username" 2>/dev/null ||
        warn "$username: could not force a password change at first login."

    local home
    home="$(student_home_path "$username")"

    chown "${username}:${username}" "$home"
    chmod 0700 "$home"

    record_credential "$username" "$password" "$display_name"

    log_action "PROVISION_FACULTY" "$username" "SUCCESS"
    success "Provisioned faculty: $username"
    PROVISIONED=$((PROVISIONED + 1))
}

# ---------------------------------------------------------------------------
# Sources
# ---------------------------------------------------------------------------

provision_from_csv() {
    local csv="$1"
    local line_number=0
    local username name

    [[ -f "$csv" ]] || die "CSV file not found: $csv"

    while IFS=',' read -r username name _rest || [[ -n "${username:-}" ]]; do
        line_number=$((line_number + 1))

        # Strip CR from spreadsheet-exported CSVs.
        username="${username//$'\r'/}"
        name="${name//$'\r'/}"
        username="${username//[[:space:]]/}"

        # Trim surrounding whitespace from the display name only.
        name="${name#"${name%%[![:space:]]*}"}"
        name="${name%"${name##*[![:space:]]}"}"

        [[ -n "$username" ]] || continue
        [[ "$username" == \#* ]] && continue

        if ((line_number == 1)) && [[ "${username,,}" == "username" ]]; then
            continue
        fi

        provision_faculty_account "$username" "${name:-Faculty}" || true
    done < "$csv"
}

provision_from_list() {
    local username

    IFS=',' read -ra requested <<< "$1"

    for username in "${requested[@]}"; do
        username="${username//[[:space:]]/}"
        [[ -n "$username" ]] || continue

        provision_faculty_account "$username" "Faculty" || true
    done
}

# ---------------------------------------------------------------------------

show_summary() {
    header "Faculty Provisioning Complete"

    printf '  %-24s %s\n' "Provisioned"    "$PROVISIONED"
    printf '  %-24s %s\n' "Failed"         "$FAILED"
    printf '  %-24s %s\n' "Faculty group"  "$FACULTY_GROUP"
    printf '  %-24s %s\n' "Total faculty"  "$(count_users_in_group "$FACULTY_GROUP")"
    printf '  %-24s %s\n' "Credentials"    "$FACULTY_CREDENTIALS"
    echo

    info "Faculty read submissions directly from ${SUBMISSION_ROOT}/<student>/"
    info "Access is granted by the g:${FACULTY_GROUP}:rX ACL on each student archive."
    echo
    warn "Passwords are in the root-only credentials file above."
    warn "A change is required at first login for newly created accounts (chage -d 0)."
    warn "Faculty must log out and back in before new group membership applies."
}

usage() {
    cat <<EOF
Usage: provision_faculty.sh [option]

  --csv FILE       Provision from a CSV file (username[,display name])
  --users a,b,c    Provision the named accounts
  -h, --help       Show this help

With no option an interactive menu is shown.
EOF
}

provision_menu() {
    header "Faculty Provisioning"

    echo "1. From CSV file"
    echo "2. Enter usernames manually"
    echo "3. Return"
    echo

    local choice
    choice="$(prompt_value "Choice")"

    case "$choice" in
        1)
            local csv
            csv="$(prompt_value "CSV file path" "${ASMS_ROOT}/data/faculty.csv")"
            provision_from_csv "$csv"
            ;;
        2)
            local input
            input="$(prompt_value "Faculty usernames (comma separated)")"
            [[ -n "$input" ]] || die "No usernames supplied."
            provision_from_list "$input"
            ;;
        3) return 0 ;;
        *) die "Invalid choice." ;;
    esac
}

main() {
    require_command useradd
    require_command usermod
    require_command chpasswd

    ensure_faculty_group
    ensure_credential_store

    case "${1:-}" in
        --csv)
            [[ -n "${2:-}" ]] || die "--csv requires a file path."
            provision_from_csv "$2"
            ;;
        --users)
            [[ -n "${2:-}" ]] || die "--users requires a comma-separated list."
            provision_from_list "$2"
            ;;
        -h|--help) usage; return 0 ;;
        "")        provision_menu ;;
        *)         usage >&2; die "Unknown option: $1" ;;
    esac

    show_summary

    ((FAILED == 0))
}

main "$@"
